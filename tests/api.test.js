// Kiểm thử luồng nghiệp bắt buộc: node tests/api.test.js
process.env.DB_FILE = ':memory:';
const app = require('../server/server.js'); const assert = require('assert');
const srv = app.listen(0); const base = `http://localhost:${srv.address().port}/api`;
const call = async (m, p, b, t) => { const r = await fetch(base + p, { method: m, headers: { 'Content-Type': 'application/json', ...(t ? { Authorization: 'Bearer ' + t } : {}) }, body: b ? JSON.stringify(b) : undefined }); return { s: r.status, d: await r.json() }; };
const login = async i => (await call('POST', '/auth/login', { identifier: i, password: '123456' })).d.token;
let n = 0; const ok = (c, m) => { assert(c, m); console.log('PASS', m); n++; };
(async () => {
  const [A, L, S] = [await login('admin@dntu.edu.vn'), await login('an.nv@dntu.edu.vn'), await login('khoa.lm@dntu.edu.vn')];
  ok((await call('GET', '/classes')).s === 401, 'Không token → 401');
  const c = (await call('POST', '/classes', { name: 'Dung sai K23', max_students: 1 }, L)).d;
  ok(/^TF-/.test(c.code), 'GV tạo lớp, sinh mã lớp');
  ok((await call('POST', '/classes', { name: 'x' }, S)).s === 403, 'SV không tạo được lớp');
  ok((await call('POST', '/classes/join', { code: 'TF-SAI' }, S)).s === 404, 'Mã sai bị backend từ chối');
  ok((await call('POST', '/classes/join', { code: c.code.toLowerCase() }, S)).d.status === 'ACTIVE', 'Tham gia bằng mã hợp lệ');
  ok((await call('POST', '/classes/join', { code: c.code }, S)).s === 409, 'Không tham gia trùng lớp');
  const a = (await call('POST', `/classes/${c.id}/assignments`, { title: 'BT1', max_score: 10, due: '2099-01-01T00:00' }, L)).d;
  ok((await call('POST', `/classes/${c.id}/assignments`, { title: 'x' }, S)).s === 403, 'SV không giao bài');
  ok((await call('POST', `/assignments/${a.id}/submit`, { action: 'draft', content: 'nháp' }, S)).d.status === 'DRAFT', 'Lưu nháp');
  const sub = (await call('POST', `/assignments/${a.id}/submit`, { content: 'ES=25' }, S)).d;
  ok(sub.status === 'SUBMITTED', 'Nộp bài');
  ok((await call('POST', `/assignments/${a.id}/submit`, { content: 'sửa' }, S)).s === 409, 'Không nộp lại khi chưa được phép');
  ok((await call('PUT', `/submissions/${sub.id}/grade`, { score: 10 }, S)).s === 403, 'SV không tự sửa điểm');
  ok((await call('PUT', `/submissions/${sub.id}/grade`, { score: 11 }, L)).s === 400, 'Điểm vượt thang bị chặn');
  ok((await call('PUT', `/submissions/${sub.id}/grade`, { score: 8, feedback: 'Tốt' }, L)).s === 200, 'GV chấm điểm');
  ok((await call('PUT', `/submissions/${sub.id}/grade`, { score: 9 }, L)).s === 200, 'GV sửa điểm');
  ok((await call('GET', `/submissions/${sub.id}/history`, null, L)).d.grades.length === 2, 'Lưu lịch sử chấm điểm');
  await call('POST', '/auth/register', { code: '999', name: 'SV2', email: 'sv2@x.vn', password: '123456' });
  const S2 = await login('sv2@x.vn');
  ok((await call('GET', `/classes/${c.id}/assignments`, null, S2)).s === 403, 'SV ngoài lớp không xem được dữ liệu lớp');
  ok((await call('POST', '/classes/join', { code: c.code }, S2)).s === 409, 'Lớp hết chỗ');
  await call('POST', '/auth/register', { code: 'GV9', name: 'x', email: 'g9@x.vn', password: '123456' });
  await call('POST', '/admin/users', { code: 'GV002', name: 'GV khác', email: 'gv2@x.vn', role: 'LECTURER' }, A);
  const L2 = await login('gv2@x.vn');
  ok((await call('PATCH', `/classes/${c.id}`, { status: 'CLOSED' }, L2)).s === 403, 'GV khác không quản lý lớp không thuộc mình');
  ok((await call('GET', '/admin/users', null, L)).s === 403, 'GV không vào được khu admin');
  ok((await call('GET', '/notifications', null, L)).d.length > 0, 'Có thông báo khi phát sinh hoạt động');
  ok((await call('GET', '/admin/backup', null, A)).d.grade_log.length === 2, 'Admin sao lưu dữ liệu');
  console.log(`\n${n} test ĐẠT`); srv.close();
})().catch(e => { console.error('FAIL', e.message); process.exit(1); });
